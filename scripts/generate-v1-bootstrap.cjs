// Generate the empty-database baseline from the installed, locked Drizzle version.
// No database access. Existing databases use the explicit additive startup manifest.
const fs = require('node:fs');
const ts = require('typescript');
const { generateDrizzleJson, generateMigration } = require('drizzle-kit/api');
(async () => {
  const schema = {};
  const compiled = ts.transpileModule(fs.readFileSync('shared/schema.ts', 'utf8'), {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
  }).outputText;
  new Function('exports', 'require', compiled)(schema, require);
  const statements = await generateMigration(generateDrizzleJson({}), generateDrizzleJson(schema));
  const output = '-- Generated by scripts/generate-v1-bootstrap.cjs from shared/schema.ts.\n'
    + '-- Empty schema ONLY; startup enforces that boundary inside its migration transaction.\n'
    + statements.join('\n').replaceAll('"public".', '') + '\n';
  if (process.argv.includes('--check')) {
    if (fs.readFileSync('migrations/v1-bootstrap.sql', 'utf8').replaceAll('\r\n', '\n') !== output) {
      throw new Error('V1 bootstrap does not match shared/schema.ts; regenerate and review');
    }
  } else fs.writeFileSync('migrations/v1-bootstrap.sql', output);
  console.log(`V1 empty-schema baseline: ${statements.length} statements`);
})().catch(error => { console.error(error.message); process.exitCode = 1; });
